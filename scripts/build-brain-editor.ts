/*
Builds public/brain-editor.html: the brain editor as one self-contained file, with its JavaScript
(engine, React and the components of components/brain-editor/) and its CSS inside. It opens from disk
(file://) without a server. Run it with `npm run build:brain-editor` after changing the editor or the
engine code it uses; the /brain-editor page of the app does not need it.
With --check it writes nothing and fails if the file is not what the code builds (brainEditorHtml.test.ts).
*/
import fs from "fs";
import path from "path";
import { build } from "esbuild";
import postcss from "postcss";
import tailwindcss from "@tailwindcss/postcss";

const root = path.resolve(__dirname, "..");
const output = path.join(root, "public", "brain-editor.html");

// only the files of the editor are scanned for Tailwind classes, so the CSS has only what it uses
const CLASS_SOURCES = [
  "components/brain-editor",
  "components/global/Button.tsx",
  "components/simulation/tabs/population/NetworkDiagram.tsx",
];

async function buildCss(): Promise<string> {
  const globals = fs.readFileSync(path.join(root, "styles", "globals.css"), "utf-8");
  if (!globals.includes('@import "tailwindcss";')) throw new Error('styles/globals.css no longer starts with @import "tailwindcss";');
  const sources = CLASS_SOURCES.map((source) => `@source "${path.join(root, source)}";`).join("\n");
  const input = globals.replace('@import "tailwindcss";', `@import "tailwindcss" source(none);\n${sources}`);
  const result = await postcss([tailwindcss({ base: root, optimize: { minify: true } })])
    .process(input, { from: path.join(root, "styles", "brain-editor.css") });
  return result.css;
}

async function buildJs(): Promise<string> {
  const result = await build({
    entryPoints: [path.join(root, "components", "brain-editor", "standalone.tsx")],
    bundle: true,
    minify: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    jsx: "automatic",
    write: false,
    legalComments: "none",
    define: { "process.env.NODE_ENV": '"production"' },
    tsconfig: path.join(root, "tsconfig.json"),
    logOverride: {
      // "use client" only means something to Next.js
      "unsupported-directive": "silent",
      // neuronTypeToString() in Neuron.ts: SENSOR and ACTION are both 1, on purpose
      "duplicate-case": "silent",
    },
  });
  return result.outputFiles[0].text;
}

// text inside <script> or <style> must not close the tag
const escapeTag = (text: string, tag: string) => text.replace(new RegExp(`</${tag}`, "gi"), `<\\/${tag}`);

// the content of public/brain-editor.html, built from the code
async function buildBrainEditorHtml(): Promise<string> {
  const [css, js] = await Promise.all([buildCss(), buildJs()]);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Brain editor - react-biosim</title>
<!-- Generated by scripts/build-brain-editor.ts (npm run build:brain-editor). Do not edit: the code is in components/brain-editor/ -->
<style>${escapeTag(css, "style")}</style>
</head>
<body class="bg-grey-dark text-white">
<div id="root"></div>
<script>${escapeTag(js, "script")}</script>
</body>
</html>
`;
}

async function main() {
  const html = await buildBrainEditorHtml();
  if (process.argv.includes("--check")) {
    const saved = fs.existsSync(output) ? fs.readFileSync(output, "utf-8") : "";
    if (saved !== html) {
      console.error(`${path.relative(root, output)} is out of date: run npm run build:brain-editor`);
      process.exit(1);
    }
    console.log(`${path.relative(root, output)} is up to date`);
    return;
  }
  fs.writeFileSync(output, html);
  console.log(`Wrote ${path.relative(root, output)} (${Math.round(html.length / 1024)} KB)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
